import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/workspace/.cloud-tools/browser/node_modules/playwright-core/index.mjs');
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = process.env.YIYU_BROWSER_OUTPUT || join(tmpdir(), 'yiyu-browser-check');
const base = process.env.YIYU_TEST_URL || 'http://127.0.0.1:8000/';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';

const sample = { name: '银杏', latin: 'Ginkgo biloba', family: 'Ginkgoaceae', genus: 'Ginkgo', summary: '植物概述 <img src=x onerror="window.injected=true"> 需实物核对。', evidence: '扇形叶与二叉叶脉可作为核对线索。', uncertain: false, sections: { morphology: '扇形叶，叶脉二叉分枝。', distribution: '按可靠资料核对分布与生境。', cultivation: '根据所在地气候和植株状况观察养护。', uses: '观赏价值需结合已确认物种说明。', culture: '文化资料需要查证来源。', similar: '对照叶片、花果和枝条确认近种差异。' } };
const imagePath = join(root, 'icon-192.png');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
mkdirSync(output, { recursive: true });
const results = [];
try {
  for (const [device, viewport] of [['desktop', { width: 1440, height: 1100 }], ['mobile', { width: 390, height: 844 }]]) {
    const context = await browser.newContext({ viewport, serviceWorkers: 'block' });
    const page = await context.newPage(); const errors = [], requests = [];
    let incomplete = false;
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/status', route => route.fulfill({ json: { ready: true, deepseek: true, plantnet: true, species: true } }));
    await page.route('**/api/ai', async route => {
      const body = route.request().postDataJSON();
      requests.push({ mode: body.mode, format: body.format, hasImage: Boolean(body.image) });
      await route.fulfill({ json: { model: 'deepseek-flash', encyclopedia: incomplete ? { name: '无效结果', sections: {} } : sample, answer: '百科正文' } });
    });
    await page.route('**/api/identify', route => route.fulfill({ json: { imagesUsed: 1, results: [{ score: 0.87, species: { commonNames: ['银杏'], scientificNameWithoutAuthor: 'Ginkgo biloba', family: { scientificName: 'Ginkgoaceae' } } }] } }));
    await page.route('https://api.inaturalist.org/**', route => route.fulfill({ json: { results: [] } }));
    await page.goto(base);
    await page.waitForFunction(() => typeof state === 'object' && state !== null && document.querySelector('#desktop-nav')?.children.length > 0);
    const goToRecognition = async () => { await page.locator('[data-nav="recognize"]:visible').first().click(); };
    await goToRecognition();
    await page.locator('[data-action="v51-deepseek-identify"]').click();
    assert.equal(await page.locator('#v53-deepseek-panel #v2-ai-question').count(), 0);
    await page.locator('#v2-ai-image').setInputFiles(imagePath);
    await page.waitForFunction(() => Boolean(ui.aiImage) && !document.getElementById('v2-ai-run')?.disabled);
    await page.locator('#v2-ai-run').click();
    await page.locator('[data-action="v54-add-ai"]').waitFor();
    assert.equal(await page.locator('#v2-ai-result .v54-chapters > details').count(), 6);
    assert.equal(await page.locator('#v2-ai-result .v54-summary img').count(), 0);
    assert.equal(await page.evaluate(() => Boolean(window.injected)), false);
    assert.deepEqual(requests[0], { mode: 'identify', format: 'encyclopedia', hasImage: true });
    await page.locator('#v2-ai-result').screenshot({ path: join(output, `${device}-encyclopedia.png`) });
    await page.locator('[data-action="v54-add-ai"]').click();
    const form = page.locator('#sighting-form');
    assert.equal(await form.locator('[name="name"]').inputValue(), sample.name);
    assert.equal(await form.locator('[name="latin"]').inputValue(), sample.latin);
    assert.equal(await form.locator('#sighting-preview img').count(), 1);
    assert.equal(await form.locator('[name="notes"]').inputValue(), '');
    const savedName = `浏览器测试-${device}`;
    await form.locator('[name="name"]').fill(savedName);
    await form.locator('[type="submit"]').click();
    await page.waitForFunction(name => state.sightings.some(s => s.name === name), savedName);
    await page.waitForFunction(() => !document.getElementById('sighting-form'));
    await page.reload();
    await page.waitForFunction(name => typeof state === 'object' && state?.sightings?.some(s => s.name === name), savedName);
    await page.locator('[data-nav="atlas"]:visible').first().click();
    const savedId = await page.evaluate(name => state.sightings.find(s => s.name === name).id, savedName);
    await page.locator(`[data-action="sighting-detail"][data-id="${savedId}"]`).first().click();
    assert.equal(await page.locator('#modal-root .v56-visit').count(), 1);
    assert.equal(await page.locator('#modal-root .v54-guide').count(), 0);
    await page.locator('[data-action="v56-open-guide"]').click();
    await page.locator('#v56-guide-content .v54-chapters').waitFor();
    assert.equal(requests.filter(request => request.mode === 'species').length, 0, 'saved recognition article is reused without a second generation');
    assert.equal(await page.locator('#modal-root .v54-chapters > details').count(), 6);
    assert.ok(await page.locator('#modal-root .v54-guide').innerText().then(s => s.includes('扇形叶')));
    assert.ok((await page.locator('#modal-root .v54-summary').innerText()).includes('植物概述'));
    assert.ok((await page.locator('#modal-root .v54-guide-head').innerText()).includes('Ginkgoaceae'));
    assert.equal(await page.locator('#modal-root .v54-evidence').count(), 0);
    await page.screenshot({ path: join(output, `${device}-saved-encyclopedia.png`) });
    await page.locator('#modal-root [data-action="close-modal"]').first().click();
    await goToRecognition();
    await page.locator('[data-action="v51-plantnet"]').click();
    assert.equal(await page.locator('#v52-plantnet-panel .v47-recognize-side').count(), 0);
    assert.equal(await page.locator('#v52-plantnet-panel .v453-capture').count(), 0);
    await page.locator('#recognize-photo').setInputFiles(imagePath);
    await page.waitForFunction(() => Boolean(ui.recognitionImage));
    await page.locator('[data-action="v52-identify-run"]:visible').first().click();
    await page.locator('[data-action="v54-add-plantnet"]').first().waitFor();
    await page.locator('[data-action="v54-add-plantnet"]').first().click();
    assert.equal(await page.locator('#sighting-form [name="name"]').inputValue(), '银杏');
    await page.locator('#modal-root [data-action="close-modal"]').first().click();
    await page.locator('[data-action="v54-plantnet-guide"]').first().click();
    await page.locator('[data-action="v54-add-open-guide"]').waitFor();
    assert.equal(await page.locator('#v54-plantnet-guide .v54-chapters > details').count(), 6);
    assert.deepEqual(requests.at(-1), { mode: 'species', format: 'encyclopedia', hasImage: false });
    await page.locator('[data-action="v54-add-open-guide"]').click();
    await page.locator('#sighting-form [name="name"]').fill(`Pl@ntNet测试-${device}`);
    await page.locator('#sighting-form [type="submit"]').click();
    await page.waitForFunction(name => state.sightings.some(s => s.name === name), `Pl@ntNet测试-${device}`);
    await page.waitForFunction(() => !document.getElementById('sighting-form'));
    assert.ok(await page.evaluate(() => state.sightings.every(s => s.image && s.images.length === 1) && Boolean(state.encyclopediaEntries['latin:ginkgo biloba'])));
    await page.locator('[data-action="v51-deepseek-identify"]').click();
    await page.locator('#v2-ai-image').setInputFiles(imagePath);
    await page.waitForFunction(() => Boolean(ui.aiImage) && !document.getElementById('v2-ai-run')?.disabled);
    incomplete = true;
    await page.locator('#v2-ai-run').click();
    await page.locator('#v2-ai-result [role="alert"]').waitFor();
    assert.equal(await page.locator('#v2-ai-result [data-action="v54-add-ai"]').count(), 0);
    assert.equal(await page.evaluate(() => state.sightings.length), 2);
    assert.deepEqual(errors, []);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${device} must not overflow horizontally`);
    results.push({ device, savedRecords: 2, chapters: 6, persistedAfterReload: true, recognitionSave: true, incompleteResponseRejected: true, pageErrors: errors.length });
    await context.close();
  }
  console.log(JSON.stringify(results, null, 2));
} finally { await browser.close(); }

import assert from 'node:assert/strict';
import { chromium } from '/workspace/.cloud-tools/browser/node_modules/playwright-core/index.mjs';
const base = process.env.YIYU_TEST_URL || 'http://127.0.0.1:8003/';
const tile = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
const point = { name: '杭州植物园', address: '浙江省 · 杭州市 · 西湖区', lat: 30.252, lon: 120.116 };
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
try {
  for (const width of [390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, serviceWorkers: 'block' });
    const page = await context.newPage(), errors = [], queries = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => {
      window.gpsCalls = 0;
      navigator.geolocation.getCurrentPosition = () => { window.gpsCalls++; };
    });
    await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ body: tile, contentType: 'image/png' }));
    await page.route('https://*.basemaps.cartocdn.com/**', route => route.fulfill({ body: tile, contentType: 'image/png' }));
    await page.route('**/api/status', route => route.fulfill({ json: { ready: true, places: true } }));
    await page.route('**/api/places?*', route => {
      const query = new URL(route.request().url()).searchParams.get('q'); queries.push(query);
      if (query === '查无此地') return route.fulfill({ json: { results: [] } });
      if (query === '接口故障') return route.fulfill({ status: 502, json: { error: '地点搜索暂时不可用，请稍后重试' } });
      return route.fulfill({ json: { results: [point, { ...point, name: '同名地点 <img src=x onerror=alert(1)>', address: '其他城市', lon: 121 } ] } });
    });
    await page.goto(base);
    await page.waitForFunction(() => typeof state === 'object' && state !== null);
    const initialGpsCalls = await page.evaluate(() => window.gpsCalls);
    await page.evaluate(() => { state.sightings = []; ui.tab = 'atlas'; render(); });
    const overview = page.locator('.v58-place-search[data-map="v56-atlas-map"]');
    assert.equal(await page.locator('#v56-atlas-map.leaflet-container').count(), 1, 'Map can be searched before the first sighting');
    await overview.locator('input').fill('杭州植物园');
    await overview.locator('input').press('Enter');
    await overview.locator('.v58-place-result').first().waitFor();
    assert.equal(await overview.locator('.v58-place-result img').count(), 0);
    await overview.locator('.v58-place-result').first().click();
    await page.locator('[data-action="v58-record-place"]').click();
    const form = page.locator('#sighting-form'), picker = form.locator('.v58-place-search');
    assert.equal(await form.locator('.v56-map, .leaflet-container, iframe').count(), 0, 'Location forms contain no map');
    assert.equal(await form.locator('[name=location]').inputValue(), point.name);
    assert.equal(Number(await form.locator('[name=lat]').inputValue()), point.lat);
    await form.locator('[name=name]').fill('我的地图发现');
    await form.locator('[name=notes]').fill('通过地点搜索添加的观察');
    await form.locator('[type=submit]').click();
    await page.waitForFunction(() => state.sightings.length === 1);
    await page.waitForFunction(() => !document.getElementById('sighting-form'));
    await page.reload();
    await page.waitForFunction(() => state?.sightings?.length === 1);
    const stored = await page.evaluate(() => state.sightings[0]);
    assert.equal(stored.location, point.name); assert.equal(stored.lat, point.lat); assert.equal(stored.lon, point.lon);
    await page.evaluate(() => { ui.tab = 'atlas'; render(); });
    assert.equal(await page.locator('#v56-atlas-map .v56-pin').count(), 1);
    await page.locator('.v56-group-card').click();
    assert.equal(await page.locator('.v56-record-page .v56-map').count(), 0);
    assert.equal(await page.locator('.v56-record-page a[href*="openstreetmap"], .v56-record-page iframe').count(), 0);
    await page.locator('[data-action="edit-sighting"]').click();
    assert.equal(Number(await form.locator('[name=lat]').inputValue()), point.lat);
    await form.locator('[name=location]').fill('接口故障');
    assert.equal(await form.locator('[name=lat]').inputValue(), '');
    await picker.locator('[data-action="v58-search-place"]').click();
    await picker.locator('.v58-search-state').filter({ hasText: '地点搜索暂时不可用' }).waitFor();
    assert.equal(await picker.locator('[data-action="v58-search-place"]').isEnabled(), true);
    await form.locator('[name=location]').fill('查无此地');
    await form.locator('[name=location]').press('Enter');
    await picker.locator('.v58-search-state').filter({ hasText: '未找到地点' }).waitFor();
    assert.equal(await form.count(), 1, 'Enter searches instead of submitting the observation');
    await form.locator('[name=location]').fill('杭州植物园');
    await picker.locator('[data-action="v58-search-place"]').click();
    await picker.locator('.v58-place-result').first().click();
    assert.equal(Number(await form.locator('[name=lon]').inputValue()), point.lon);
    await page.screenshot({ path: `/tmp/yiyu-v58-${width}-picker.png` });
    assert.equal(await form.locator('.v56-map, .leaflet-container, iframe').count(), 0);
    await form.locator('[type=submit]').click();
    await page.waitForFunction(() => !document.getElementById('sighting-form'));
    const data = await page.evaluate(async () => JSON.parse(await (await yiyuBuildFile()).file.text()));
    assert.equal(data.sightings[0].lon, point.lon);
    assert.equal(await page.evaluate(() => window.gpsCalls), initialGpsCalls, 'Place selection does not request GPS');
    await page.locator('.v56-group-card').click();
    await page.locator('[data-action="edit-sighting"]').click();
    await page.route('https://nominatim.openstreetmap.org/reverse?*', route => route.fulfill({ json: { address: { state: '浙江省', city: '杭州市', suburb: 'GPS测试地点' } } }));
    await page.evaluate(() => {
      navigator.geolocation.getCurrentPosition = success => success({ coords: { latitude: 30.3, longitude: 120.2, accuracy: 8 } });
    });
    await form.locator('[data-action="v2-geolocate"]').click();
    await page.waitForFunction(() => document.querySelector('#v2-coord-state').textContent.includes('已选择：'));
    assert.equal(Number(await form.locator('[name=lat]').inputValue()), 30.3);
    assert.equal(Number(await form.locator('[name=lon]').inputValue()), 120.2);
    await page.evaluate(() => {
      navigator.geolocation.getCurrentPosition = (success, fail) => fail({ code: 1 });
    });
    await form.locator('[data-action="v2-geolocate"]').click();
    await page.waitForFunction(() => document.querySelector('#v2-coord-state').textContent.includes('位置权限被拒绝'));
    assert.equal(Number(await form.locator('[name=lat]').inputValue()), 30.3);
    assert.equal(await form.locator('[name=location]').evaluate(input => input.readOnly), false);
    assert.deepEqual(errors, []);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    console.log(`${width}px: map only on overview, search, persistence, edit, errors, Enter, backup, GPS success and denial passed (${queries.length} searches)`);
    await context.close();
  }
} finally { await browser.close(); }
